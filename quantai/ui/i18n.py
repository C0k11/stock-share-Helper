def tr(lang: str, key: str, **fmt) -> str:
    """取词条（缺失回退中文 → 再缺返回 key）。fmt 出错原样返回，绝不炸渲染。"""
    s = STRINGS.get(lang, {}).get(key) or STRINGS["zh"].get(key) or key
    if fmt:
        try:
            return s.format(**fmt)
        except Exception:  # noqa: BLE001
            return s
    return s
